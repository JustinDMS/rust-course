//! `course build`: writes the static site's data file.
//!
//! The frontend in `docs/` loads `docs/data/course.js`, a single script that
//! assigns the whole course (chapters, cards, exercises with their starter
//! code, appended tests, hints and solutions) to `window.COURSE`. A script
//! rather than JSON so that the site also works when opened straight from
//! the file system, where `fetch` is not allowed.

use crate::content::Content;
use anyhow::{Context, Result};
use std::path::{Path, PathBuf};

pub struct Summary {
    pub path: PathBuf,
    pub bytes: usize,
    pub chapters: usize,
    pub cards: usize,
    pub exercises: usize,
    pub total_xp: u32,
}

pub fn build(content: &Content, docs: &Path) -> Result<Summary> {
    let course = content.course()?;
    let json = serde_json::to_string(&course)?;
    let text = format!(
        "// Generated by `cargo run -p course -- build` from content/, exercises/ and solutions/.\n// Do not edit by hand.\nwindow.COURSE = {json};\n"
    );
    let dir = docs.join("data");
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    let path = dir.join("course.js");
    std::fs::write(&path, &text).with_context(|| format!("writing {}", path.display()))?;
    Ok(Summary {
        path,
        bytes: text.len(),
        chapters: course.chapters.len(),
        cards: course.chapters.iter().map(|c| c.cards.len()).sum(),
        exercises: course.exercises.len(),
        total_xp: course.total_xp,
    })
}
